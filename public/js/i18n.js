const ID = {};

let current = 'id';
const DICTS = { id: ID, en: EN };

/** Bahasa aktif. */
export const lang = () => current;

export function setLang(next) {
  current = next === 'en' ? 'en' : 'id';
  document.documentElement.lang = current;
  try { localStorage.setItem('qhse-lang', current); } catch { /* mode privat */ }
  return current;
}

/** Bahasa tersimpan di peramban, dipakai sebelum profil pengguna termuat. */
export function storedLang() {
  try {
    const saved = localStorage.getItem('qhse-lang');
    return saved === 'en' || saved === 'id' ? saved : null;
  } catch {
    return null;
  }
}

/** Terjemahan satu teks. Yang belum ada di kamus tampil apa adanya. */
export function t(text) {
  if (typeof text !== 'string') return text;
  return DICTS[current][text] ?? text;
}

/** Untuk kalimat bersisipan: tp('Menyunting: {n}', { n: nama }). */
export function tp(text, values = {}) {
  return String(t(text)).replace(/\{(\w+)\}/g, (_, key) => (values[key] ?? `{${key}}`));
}
